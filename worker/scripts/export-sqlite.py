#!/usr/bin/env python3
"""
Convert an Applitrack SQLite file (the FastAPI backend's database) into SQL that
D1 can import.

Why a script instead of `sqlite3 .dump`:
  * the old schema has a `track_status_change` trigger and the
    `application_status_flow` view, neither of which should be recreated (the
    Worker writes history itself, and the view is created by 0001_init.sql),
  * datetimes were stored as "YYYY-MM-DD HH:MM:SS.ffffff" and must become
    fixed-width ISO-8601 UTC ("YYYY-MM-DDTHH:MM:SS.sssZ"),
  * primary keys must be preserved, because attachment_key embeds the
    application id (attachments/<user>/<id>/<file>.pdf in R2).

Usage:
    python3 worker/scripts/export-sqlite.py backend/data/applitrack.db > /tmp/applitrack-data.sql
    cd worker && npx wrangler d1 execute applitrack --remote --file=/tmp/applitrack-data.sql

Run the migrations first; this only inserts rows.
"""

from __future__ import annotations

import sqlite3
import sys
from datetime import datetime, timezone
from pathlib import Path


def to_d1_datetime(value: object) -> str | None:
    """Convert a SQLAlchemy-stored datetime into ISO-8601 UTC text."""
    if value is None or value == "":
        return None

    raw = str(value).strip().replace(" ", "T", 1)
    try:
        parsed = datetime.fromisoformat(raw)
    except ValueError:
        return str(value)

    if parsed.tzinfo is not None:
        parsed = parsed.astimezone(timezone.utc).replace(tzinfo=None)

    return f"{parsed.strftime('%Y-%m-%dT%H:%M:%S')}.{parsed.microsecond // 1000:03d}Z"


def sql_literal(value: object) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2

    path = Path(sys.argv[1])
    if not path.exists():
        print(f"No such database: {path}", file=sys.stderr)
        return 1

    connection = sqlite3.connect(f"file:{path}?mode=ro", uri=True)
    connection.row_factory = sqlite3.Row

    applications = connection.execute(
        """
        SELECT id, created_at, user_id, applied_at, expires_at, position, company,
               status, link, attachment_key
        FROM applications
        ORDER BY id
        """
    ).fetchall()

    history = connection.execute(
        """
        SELECT id, created_at, application_id, user_id, from_status, to_status
        FROM application_status_history
        ORDER BY id
        """
    ).fetchall()

    print("-- Generated by worker/scripts/export-sqlite.py from " + path.name)
    print("-- Apply after: npx wrangler d1 migrations apply applitrack --remote")
    # No BEGIN/COMMIT: `wrangler d1 execute --file` rejects explicit
    # transactions (D1 owns the transaction boundary).

    for row in applications:
        values = [
            row["id"],
            to_d1_datetime(row["created_at"]),
            row["user_id"],
            to_d1_datetime(row["applied_at"]),
            to_d1_datetime(row["expires_at"]),
            row["position"],
            row["company"],
            row["status"],
            row["link"],
            row["attachment_key"],
        ]
        print(
            "INSERT INTO applications (id, created_at, user_id, applied_at, expires_at, "
            "position, company, status, link, attachment_key) VALUES ("
            + ", ".join(sql_literal(value) for value in values)
            + ");"
        )

    for row in history:
        values = [
            row["id"],
            to_d1_datetime(row["created_at"]),
            row["application_id"],
            row["user_id"],
            row["from_status"],
            row["to_status"],
        ]
        print(
            "INSERT INTO application_status_history (id, created_at, application_id, user_id, "
            "from_status, to_status) VALUES ("
            + ", ".join(sql_literal(value) for value in values)
            + ");"
        )

    print(
        f"-- {len(applications)} applications, {len(history)} history rows",
        file=sys.stderr,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
